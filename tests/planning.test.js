'use strict';
const assert = require('node:assert/strict');
const planning = require('../planning.js');
for (const fee of ['Free', 'Free participation and registration', '0 BDT', '৳ 0', 'বিনামূল্যে']) assert.equal(planning.isExplicitlyFree(fee), true, fee);
for (const fee of ['Not specified', 'No entry fee listed', 'Free accounts available; entry fee unknown', 'Not free', 'Free registration, paid participation', '500 BDT']) assert.equal(planning.isExplicitlyFree(fee), false, fee);
const now = Date.parse('2026-10-15T00:00:00Z');
assert.equal(planning.matchesDeadline({ deadline: null }, 'exclude-closed', now), true);
assert.equal(planning.matchesDeadline({ deadline: null }, 'future', now), false);
assert.equal(planning.matchesDeadline({ deadline: '2026-10-14T00:00:00Z' }, 'exclude-closed', now), false);
assert.equal(planning.matchesDeadline({ deadline: '2026-10-20T00:00:00Z', status: 'confirmed' }, '7', now), true);
assert.equal(planning.matchesDeadline({ deadline: '2026-11-01T00:00:00Z', status: 'confirmed' }, '7', now), false);
assert.equal(planning.matchesDeadline({ deadline: '2026-11-01T00:00:00Z', status: 'cancelled' }, '30', now), false);
assert.equal(planning.zonedLocalToISO('2030-01-20T09:00', 'Asia/Dhaka'), '2030-01-20T03:00:00.000Z');
assert.equal(planning.zonedLocalToISO('2030-01-20T09:00', 'Asia/Kathmandu'), '2030-01-20T03:15:00.000Z');
assert.equal(planning.dateOnlyToISO('2030-01-20', 'Asia/Dhaka'), '2030-01-20T00:00:00+06:00');
assert.equal(planning.dateOnlyToISO('2030-01-20', 'Europe/Helsinki'), '2030-01-20T00:00:00+02:00');
assert.equal(planning.shiftDay('2028-02-28', 1), '2028-02-29');
assert.equal(planning.shiftDay('2028-02-29', 1), '2028-03-01');
assert.equal(planning.localParts('2030-01-20T03:00:00Z', 'Asia/Dhaka'), '2030-01-20T09:00:00');
assert.throws(() => planning.zonedLocalToISO('2026-03-08T02:30', 'America/New_York'), /does not exist/);
assert.throws(() => planning.zonedLocalToISO('2026-11-01T01:30', 'America/New_York'), /occurs twice/);
assert.throws(() => planning.zonedLocalToISO('2026-02-30T12:00', 'UTC'), /valid/);
assert.throws(() => planning.zonedLocalToISO('2026-11-01T25:00', 'UTC'), /valid/);
assert.throws(() => planning.dateOnlyToISO('2026-02-30', 'UTC'), /valid/);
assert.throws(() => planning.zonedLocalToISO('2030-01-20T09:00', 'Mars/Olympus'), /timezone/);
console.log('PASS planning: explicit free fees, deadline windows, timezone conversion, all-day dates, leap days, and DST ambiguity.');
